#define NGLYPH(t) ((int)(sizeof t / sizeof t[0]))

unsigned char ui_face8[NFACE][128][8], ui_face16[128][16];
unsigned char ui_has8[NFACE][128], ui_has16[128];

static int bar_row(const char *r) {                 /* a row with a run of four or more: a bar, not to be thickened */
    int run = 0, best = 0;
    for (; *r; r++) { run = *r == '#' ? run + 1 : 0; if (run > best) best = run; }
    return best >= 4;
}

/* the faces from their strings; FACE_INSC's 8x16 from its 8x8, stretched to ten rows by doubling three rows that
 * are no bar (a first draft, for the sheet: the 8x16 is to be drawn by hand once the look is settled) */
void ui_face_init(void) {
    static int done;
    if (done) return;
    done = 1;
    const char *const (*T[2])[8] = { INSC8, BODY8 };
    int N[2] = { NGLYPH(INSC8), NGLYPH(BODY8) }, F[2] = { FACE_INSC, FACE_BODY };
    for (int t = 0; t < 2; t++)
        for (int g = 0; g < N[t]; g++) {
            unsigned ch = (unsigned char)T[t][g][0][0];
            if (ch >= 128) continue;
            for (int r = 0; r < 7; r++) {
                unsigned b = 0;
                for (int c = 0; T[t][g][r + 1][c]; c++) if (T[t][g][r + 1][c] == '#') b |= 0x80u >> c;
                ui_face8[F[t]][ch][r] = (unsigned char)b;
            }
            ui_has8[F[t]][ch] = 1;
            if (t != 0) continue;
            int dup[7] = { 0 }, cand[5], nc = 0;
            static const int PREF[5] = { 2, 4, 1, 5, 3 };
            for (int k = 0; k < 5; k++) if (!bar_row(T[t][g][PREF[k] + 1])) cand[nc++] = PREF[k];
            for (int k = 0; k < 3; k++) dup[nc ? cand[k % nc] : PREF[k]]++;
            int o = 2;
            for (int r = 0; r < 7; r++)
                for (int k = 0; k <= dup[r] && o < 12; k++) ui_face16[ch][o++] = ui_face8[FACE_INSC][ch][r];
            ui_has16[ch] = 1;
        }
    for (int f = FACE_INSC; f <= FACE_BODY; f++) ui_has8[f][' '] = 1;   /* a space is a space */
    ui_has16[' '] = 1;
}

