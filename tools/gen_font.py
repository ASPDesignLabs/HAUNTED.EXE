#!/usr/bin/env python3
"""Rasterise the pixel-exact IBM VGA / BIOS fonts into C tables.

Source fonts: "The Ultimate Oldschool PC Font Pack" by VileR (CC BY-SA 4.0),
see third_party/font/. The Px437 TrueType outlines follow the original pixel
grid, so rendering them at their native pixel height with anti-aliasing off
gives the original bitmaps back exactly.

Usage:  python3 tools/gen_font.py > src/font_vga.c
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONTDIR = os.path.join(HERE, "..", "third_party", "font")

# CP437 control-range codes render as graphics glyphs in the VGA font.
LOW = {
    0x01: 0x263A, 0x02: 0x263B, 0x03: 0x2665, 0x04: 0x2666, 0x05: 0x2663,
    0x06: 0x2660, 0x07: 0x2022, 0x08: 0x25D8, 0x09: 0x25CB, 0x0A: 0x25D9,
    0x0B: 0x2642, 0x0C: 0x2640, 0x0D: 0x266A, 0x0E: 0x266B, 0x0F: 0x263C,
    0x10: 0x25BA, 0x11: 0x25C4, 0x12: 0x2195, 0x13: 0x203C, 0x14: 0x00B6,
    0x15: 0x00A7, 0x16: 0x25AC, 0x17: 0x21A8, 0x18: 0x2191, 0x19: 0x2193,
    0x1A: 0x2192, 0x1B: 0x2190, 0x1C: 0x221F, 0x1D: 0x2194, 0x1E: 0x25B2,
    0x1F: 0x25BC, 0x7F: 0x2302,
}


def codepoint(code):
    if code == 0:
        return 0x20
    if code in LOW:
        return LOW[code]
    return ord(bytes([code]).decode("cp437"))


def raster(ttf, px, w, h):
    font = ImageFont.truetype(os.path.join(FONTDIR, ttf), px)
    font.fontmode = "1"                      # no anti-aliasing
    rows = []
    for code in range(256):
        img = Image.new("1", (w, h), 0)
        ImageDraw.Draw(img).text((0, 0), chr(codepoint(code)), font=font, fill=1)
        glyph = []
        for y in range(h):
            b = 0
            for x in range(w):
                if img.getpixel((x, y)):
                    b |= 0x80 >> x
            glyph.append(b)
        rows.append(glyph)
    return rows


def emit(name, rows, h):
    print("const unsigned char %s[256][%d] = {" % (name, h))
    for code, g in enumerate(rows):
        print("    /*%02X*/ {%s}," % (code, ",".join("0x%02X" % b for b in g)))
    print("};")


def main():
    vga = raster("Px437_IBM_VGA_8x16.ttf", 16, 8, 16)
    bios = raster("Px437_IBM_BIOS.ttf", 8, 8, 8)
    print("/* Generated by tools/gen_font.py - do not edit.")
    print(" * Glyph bitmaps rasterised from the Px437 IBM VGA 8x16 and IBM BIOS 8x8")
    print(" * fonts of The Ultimate Oldschool PC Font Pack by VileR (CC BY-SA 4.0).")
    print(" * See third_party/font/LICENSE-oldschool-pc-font-pack.txt. */")
    print('#include "core.h"')
    print()
    emit("font_vga16", vga, 16)
    print()
    emit("font_bios8", bios, 8)
    sys.stderr.write("A (0x41) as rendered:\n")
    for b in vga[0x41]:
        sys.stderr.write("".join("#" if b & (0x80 >> i) else "." for i in range(8)) + "\n")


if __name__ == "__main__":
    main()
